create view public.product_costs with (security_invoker = true) as
select
  p.id,
  p.organization_id,
  p.sale_price,
  p.labor_minutes,
  p.labor_cost,
  p.other_cost,
  round((coalesce(sum(ri.quantity * i.package_cost / nullif(i.package_quantity, 0)), 0) / p.yield_quantity + p.labor_cost + p.other_cost), 2) as unit_cost,
  round(p.sale_price - (coalesce(sum(ri.quantity * i.package_cost / nullif(i.package_quantity, 0)), 0) / p.yield_quantity + p.labor_cost + p.other_cost), 2) as unit_profit,
  case when p.sale_price > 0 then round(100 * (p.sale_price - (coalesce(sum(ri.quantity * i.package_cost / nullif(i.package_quantity, 0)), 0) / p.yield_quantity + p.labor_cost + p.other_cost)) / p.sale_price, 1) else 0 end as margin_percent
from public.products p
left join public.recipe_items ri on ri.product_id = p.id
left join public.ingredients i on i.id = ri.ingredient_id
group by p.id;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'categories', 'suppliers', 'ingredients', 'products', 'recipe_items',
    'customers', 'orders', 'order_items', 'payments', 'expenses',
    'purchases', 'purchase_items', 'inventory_movements',
    'production_batches', 'campaigns'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('grant select, insert, update, delete on public.%I to authenticated', table_name);
    execute format('create policy "members read %1$I" on public.%1$I for select to authenticated using ((select public.is_org_member(organization_id)))', table_name);
    execute format('create policy "admins manage %1$I" on public.%1$I for all to authenticated using ((select public.is_org_admin(organization_id))) with check ((select public.is_org_admin(organization_id)))', table_name);
  end loop;

  foreach table_name in array array['customers', 'orders', 'order_items', 'payments', 'production_batches', 'inventory_movements'] loop
    execute format('create policy "members manage %1$I" on public.%1$I for all to authenticated using ((select public.is_org_member(organization_id))) with check ((select public.is_org_member(organization_id)))', table_name);
  end loop;
end $$;

grant select on public.product_costs to authenticated;

create or replace function public.register_sale(
  p_organization_id uuid,
  p_product_id uuid,
  p_quantity numeric,
  p_customer_id uuid default null,
  p_discount numeric default 0,
  p_due_at timestamptz default null,
  p_delivery_type text default 'pickup',
  p_notes text default null,
  p_is_sale boolean default false,
  p_payment_amount numeric default 0,
  p_payment_method text default 'pix'
)
returns uuid
language plpgsql
set search_path = ''
as $$
declare
  product_row record;
  order_id uuid;
  order_total numeric(12,2);
begin
  if not public.is_org_member(p_organization_id) then
    raise exception 'Acesso negado à organização.' using errcode = '42501';
  end if;
  if p_quantity <= 0 or p_discount < 0 then
    raise exception 'Quantidade e desconto inválidos.' using errcode = '22023';
  end if;

  select p.id, p.name, p.sale_price, coalesce(c.unit_cost, 0) as unit_cost
    into product_row
    from public.products p
    left join public.product_costs c on c.id = p.id
   where p.id = p_product_id and p.organization_id = p_organization_id and p.is_active;
  if not found then
    raise exception 'Produto não encontrado ou inativo.' using errcode = 'P0002';
  end if;

  order_total := round(product_row.sale_price * p_quantity, 2) - p_discount;
  if order_total < 0 or p_payment_amount < 0 or p_payment_amount > order_total then
    raise exception 'Confira o desconto e o valor recebido.' using errcode = '22023';
  end if;

  insert into public.orders (organization_id, customer_id, status, delivery_type, due_at, subtotal, discount, total, notes, created_by)
  values (p_organization_id, p_customer_id, case when p_is_sale then 'delivered' else 'confirmed' end,
          p_delivery_type, p_due_at, round(product_row.sale_price * p_quantity, 2), p_discount, order_total, p_notes, auth.uid())
  returning id into order_id;

  insert into public.order_items (organization_id, order_id, product_id, product_name_snapshot, quantity, unit_price_snapshot, unit_cost_snapshot, line_total)
  values (p_organization_id, order_id, product_row.id, product_row.name, p_quantity, product_row.sale_price,
          product_row.unit_cost, round(product_row.sale_price * p_quantity, 2));

  if p_payment_amount > 0 then
    insert into public.payments (organization_id, order_id, amount, method)
    values (p_organization_id, order_id, p_payment_amount, p_payment_method);
  end if;
  return order_id;
end;
$$;

create or replace function public.register_purchase(
  p_organization_id uuid,
  p_ingredient_id uuid,
  p_package_quantity numeric,
  p_package_cost numeric,
  p_supplier_id uuid default null,
  p_notes text default null
)
returns uuid
language plpgsql
set search_path = ''
as $$
declare
  purchase_id uuid;
  unit_cost numeric(12,4);
begin
  if not public.is_org_admin(p_organization_id) then
    raise exception 'Somente administradores podem registrar compras.' using errcode = '42501';
  end if;
  if p_package_quantity <= 0 or p_package_cost < 0 then
    raise exception 'Quantidade e custo da compra inválidos.' using errcode = '22023';
  end if;

  select round(p_package_cost / p_package_quantity, 4) into unit_cost
    from public.ingredients
   where id = p_ingredient_id and organization_id = p_organization_id and is_active;
  if not found then
    raise exception 'Insumo não encontrado ou inativo.' using errcode = 'P0002';
  end if;

  insert into public.purchases (organization_id, supplier_id, total, notes, created_by)
  values (p_organization_id, p_supplier_id, p_package_cost, p_notes, auth.uid())
  returning id into purchase_id;
  insert into public.purchase_items (organization_id, purchase_id, ingredient_id, package_quantity, package_cost)
  values (p_organization_id, purchase_id, p_ingredient_id, p_package_quantity, p_package_cost);
  update public.ingredients set package_quantity = p_package_quantity, package_cost = p_package_cost,
    supplier_id = coalesce(p_supplier_id, supplier_id), stock_quantity = stock_quantity + p_package_quantity,
    updated_at = now()
   where id = p_ingredient_id and organization_id = p_organization_id;
  insert into public.inventory_movements (organization_id, ingredient_id, movement_type, quantity_delta, unit_cost_snapshot, notes, created_by)
  values (p_organization_id, p_ingredient_id, 'purchase', p_package_quantity, unit_cost, p_notes, auth.uid());
  return purchase_id;
end;
$$;

create or replace function public.adjust_inventory(
  p_organization_id uuid,
  p_ingredient_id uuid,
  p_quantity_delta numeric,
  p_notes text default null
)
returns void
language plpgsql
set search_path = ''
as $$
declare
  current_stock numeric;
  unit_cost numeric(12,4);
begin
  if not public.is_org_member(p_organization_id) then
    raise exception 'Acesso negado à organização.' using errcode = '42501';
  end if;
  if p_quantity_delta = 0 then
    raise exception 'Informe uma variação de estoque diferente de zero.' using errcode = '22023';
  end if;
  select stock_quantity, round(package_cost / nullif(package_quantity, 0), 4)
    into current_stock, unit_cost
    from public.ingredients
   where id = p_ingredient_id and organization_id = p_organization_id and is_active
   for update;
  if not found or current_stock + p_quantity_delta < 0 then
    raise exception 'Insumo inexistente ou saldo insuficiente.' using errcode = '22023';
  end if;
  update public.ingredients set stock_quantity = stock_quantity + p_quantity_delta, updated_at = now()
   where id = p_ingredient_id and organization_id = p_organization_id;
  insert into public.inventory_movements (organization_id, ingredient_id, movement_type, quantity_delta, unit_cost_snapshot, notes, created_by)
  values (p_organization_id, p_ingredient_id, 'adjustment', p_quantity_delta, unit_cost, p_notes, auth.uid());
end;
$$;

create or replace function public.complete_production(
  p_batch_id uuid,
  p_produced_quantity numeric,
  p_loss_quantity numeric default 0
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  batch_row record;
  recipe_row record;
  used_quantity numeric(12,3);
begin
  select b.* into batch_row
    from public.production_batches b
   where b.id = p_batch_id
   for update;
  if not found or not public.is_org_member(batch_row.organization_id) then
    raise exception 'Lote não encontrado ou acesso negado.' using errcode = '42501';
  end if;
  if batch_row.status = 'completed' or p_produced_quantity <= 0 or p_loss_quantity < 0 then
    raise exception 'Confira o status e as quantidades do lote.' using errcode = '22023';
  end if;

  for recipe_row in
    select ri.ingredient_id, ri.quantity, i.stock_quantity,
           round(i.package_cost / nullif(i.package_quantity, 0), 4) as unit_cost,
           p.yield_quantity
      from public.recipe_items ri
      join public.ingredients i on i.id = ri.ingredient_id and i.organization_id = batch_row.organization_id
      join public.products p on p.id = ri.product_id and p.organization_id = batch_row.organization_id
     where ri.product_id = batch_row.product_id and ri.organization_id = batch_row.organization_id
  loop
    used_quantity := round(recipe_row.quantity * (p_produced_quantity + p_loss_quantity) / recipe_row.yield_quantity, 3);
    if recipe_row.stock_quantity < used_quantity then
      raise exception 'Estoque insuficiente para concluir a produção.' using errcode = '22023';
    end if;
    update public.ingredients set stock_quantity = stock_quantity - used_quantity, updated_at = now()
     where id = recipe_row.ingredient_id and organization_id = batch_row.organization_id;
    insert into public.inventory_movements (organization_id, ingredient_id, movement_type, quantity_delta, unit_cost_snapshot, notes, created_by)
    values (batch_row.organization_id, recipe_row.ingredient_id, 'production', -used_quantity, recipe_row.unit_cost,
            'Consumo do lote de produção', auth.uid());
  end loop;

  update public.production_batches
     set produced_quantity = p_produced_quantity, loss_quantity = p_loss_quantity,
         status = 'completed', updated_at = now()
   where id = p_batch_id;
end;
$$;

