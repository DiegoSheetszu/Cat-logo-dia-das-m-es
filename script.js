const productsGrid = document.querySelector("#productsGrid");
const extrasGrid = document.querySelector("#extrasGrid");

function renderProducts() {
  products.forEach((product, index) => {
    const heroImage = product.images[0];
    const article = document.createElement("article");
    article.className = "product-card reveal";
    article.style.transitionDelay = `${index * 80}ms`;
    article.innerHTML = `
      <figure class="product-image">
        <div class="product-main-image">
          <img src="${heroImage.src}" alt="${heroImage.alt}" />
        </div>
      </figure>
      <div class="product-copy">
        <div class="product-meta">
          <div>
            <h3>${product.name}</h3>
            <p class="tag">${product.tag}</p>
          </div>
          <p class="price">${product.price}</p>
        </div>
        <p>${product.description}</p>
        <ul class="composition-list">
          ${product.composition.map((item) => `<li>${item}</li>`).join("")}
        </ul>
        <div class="product-thumbs product-thumbs-inline">
          ${product.images
            .map(
              (image, imageIndex) => `
                <button
                  class="product-thumb ${imageIndex === 0 ? "is-active" : ""}"
                  type="button"
                  data-image="${image.src}"
                  data-alt="${image.alt}"
                >
                  <img src="${image.src}" alt="${image.alt}" />
                  <span class="product-thumb-label">${image.label}</span>
                </button>
              `
            )
            .join("")}
        </div>
      </div>
    `;
    productsGrid.appendChild(article);
  });
}

function renderExtras() {
  extras.forEach((extra, index) => {
    const article = document.createElement("article");
    article.className = "extra-card reveal";
    article.style.transitionDelay = `${index * 70}ms`;
    article.innerHTML = `
      <h3>${extra.name}</h3>
      <p>${extra.description}</p>
      <p class="extra-price">${extra.price}</p>
    `;
    extrasGrid.appendChild(article);
  });
}

function setupReveal() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.18 }
  );

  document.querySelectorAll(".reveal").forEach((element) => {
    observer.observe(element);
  });
}

function setupProductGalleries() {
  document.querySelectorAll(".product-card").forEach((card) => {
    const mainImage = card.querySelector(".product-main-image img");
    const thumbs = card.querySelectorAll(".product-thumb");

    thumbs.forEach((thumb) => {
      thumb.addEventListener("click", () => {
        thumbs.forEach((item) => item.classList.remove("is-active"));
        thumb.classList.add("is-active");
        mainImage.style.opacity = "0.5";
        mainImage.src = thumb.dataset.image;
        mainImage.alt = thumb.dataset.alt;
      });
    });

    mainImage.addEventListener("load", () => {
      mainImage.style.opacity = "1";
    });
  });
}

renderProducts();
renderExtras();
setupReveal();
setupProductGalleries();
